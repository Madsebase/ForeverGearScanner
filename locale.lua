    [0] = "Poor", [1] = "Common", [2] = "Uncommon",
    [3] = "Rare", [4] = "Epic", [5] = "Legendary",
}

function AGS.GetQualityLabel(qId)
    local name = _G["ITEM_QUALITY" .. qId .. "_DESC"] or FALLBACK_QUALITY_NAMES[qId] or ("Quality " .. qId)
    local hex
    if C_Item and C_Item.GetItemQualityColor then
        local _, _, _, h = C_Item.GetItemQualityColor(qId)
        hex = h
    end
    if not hex or hex == "" then
        hex = FALLBACK_QUALITY_HEX[qId] or "FFFFFFFF"
    elseif string.len(hex) == 6 then
        hex = "FF" .. hex
    end
    return "|c" .. hex .. name .. "|r"
end

