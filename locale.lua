function AGS.GetStatDisplayName(canonicalKey)
    if not canonicalKey then return "" end
    local lower = string.lower(canonicalKey)
    if activeStats[lower] then
        return activeStats[lower]
    end
    return (string.gsub(" " .. lower, "%s(%l)", function(c) return " " .. string.upper(c) end):sub(2))
end

-- Build localized stat alias lookup (maps localized names & Blizzard _SHORT globals -> canonical keys)
AGS.LocalizedStatAliases = {}
local function RegisterAlias(raw, canonical)
    if raw and raw ~= "" and canonical then
        local lower = string.lower(NormalizeSpaces(raw))
        lower = string.gsub(lower, "%.+$", "")
        lower = string.gsub(lower, "^[ \t\r\n]*(.-)[ \t\r\n]*$", "%1")
        if lower ~= "" then
            AGS.LocalizedStatAliases[lower] = canonical
        end
    end
end

for k, v in pairs(activeStats) do
    RegisterAlias(v, k)
end

