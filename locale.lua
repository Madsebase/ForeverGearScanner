local _, AGS = ...
if not AGS then return end

local LOCALE = (GetLocale and GetLocale()) or "enUS"
if LOCALE == "enGB" then LOCALE = "enUS" end
AGS.Locale = LOCALE

local function NormalizeSpaces(text)
    if not text then return "" end
    text = string.gsub(text, "\194\160", " ")
    return text
end

local function EscapePattern(text)
    return (string.gsub(text, "([%(%)%.%%%+%-%*%?%[%]%^%$])", "%%%1"))
end

function AGS.TemplateToPattern(tmpl, isSingleFloat)
    if not tmpl or tmpl == "" then return nil end
    local s = NormalizeSpaces(tmpl)
    -- Strip WoW plural grammar markers e.g. |4предмет:предмета:предметов;
    s = string.gsub(s, "|4[^;]+;", "__PLURAL__")
    s = EscapePattern(s)
    s = string.gsub(s, "__PLURAL__", ".-")
    local numCap = isSingleFloat and "([%d%.,]+)" or "([%d%., ]+)"
    s = string.gsub(s, "%%%%%d*%$?[sd]", function() return numCap end)
    s = string.gsub(s, "%%%%%d*%.?%d*f", function() return "([%d%.,]+)" end)
    s = string.gsub(s, "%%%%c", function() return "[%+%-]?" end)
    return "^" .. s .. "$"
end

---------------------------------------------------------------------------
-- Number Parsing Helpers (Locale-aware thousands & decimal separators)
---------------------------------------------------------------------------
function AGS.ParseNumber(str, allowDecimal)
    if not str then return 0 end
    str = NormalizeSpaces(tostring(str))
    str = string.gsub(str, "[ \t\r\n]+", "")
    if str == "" then return 0 end

    local hasDot = string.find(str, ".", 1, true) ~= nil
    local hasComma = string.find(str, ",", 1, true) ~= nil

    if hasDot and hasComma then
        -- e.g. "1.234,5" (EU) or "1,234.5" (US)
        local lastDot = string.match(str, ".*()%.")
        local lastComma = string.match(str, ".*(),")
        if lastComma > lastDot then
            str = string.gsub(str, "%.", "")
            str = string.gsub(str, ",", ".")
        else
            str = string.gsub(str, ",", "")
        end
    elseif hasComma then
        if allowDecimal or not string.match(str, "^%d+,%d%d%d$") then
            str = string.gsub(str, ",", ".")
        else
            str = string.gsub(str, ",", "")
        end
    elseif hasDot then
        if not allowDecimal and string.match(str, "^%d+%.%d%d%d$") then
            str = string.gsub(str, "%.", "")
        end
    end

    return tonumber(str) or 0
end

